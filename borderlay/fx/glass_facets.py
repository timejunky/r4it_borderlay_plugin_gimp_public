class GlassFacetsHelper:

    @staticmethod
    def build_glass_gradmap(rgb):
        _m0151 = tuple((int(c) for c in rgb))
        return (_m0151,) * 7

    @staticmethod
    def _m0478(rgb):
        return rgb

    @staticmethod
    def _m0155(*_args, **_kwargs):
        return {}

    @staticmethod
    def _m0208(*_args, **_kwargs):
        return None

    @staticmethod
    def _m0153(rgb):
        return {'base': rgb}
