class GlassFacetsHelper:

    @staticmethod
    def build_glass_gradmap(rgb):
        _m0170 = tuple((int(c) for c in rgb))
        return (_m0170,) * 7

    @staticmethod
    def _m0519(rgb):
        return rgb

    @staticmethod
    def _m0174(*_args, **_kwargs):
        return {}

    @staticmethod
    def _m0233(*_args, **_kwargs):
        return None

    @staticmethod
    def _m0172(rgb):
        return {'base': rgb}
